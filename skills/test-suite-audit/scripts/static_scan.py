def non_empty_literal(node: ast.AST, known: set[str]) -> bool:
    """True when an iterable cannot be empty: a non-empty literal, a name bound to one, or range() of constants."""
    if isinstance(node, (ast.List, ast.Tuple, ast.Set)):
        return bool(node.elts)
    if isinstance(node, ast.Dict):
        return bool(node.keys)
    if isinstance(node, ast.Name):
        return node.id in known
    if isinstance(node, ast.Call):
        name = last_name(node.func)
        if name in ("enumerate", "zip", "sorted", "reversed", "list", "tuple", "set", "product", "permutations", "combinations") and node.args:
            return all(non_empty_literal(a, known) for a in node.args)
        if name == "range" and node.args:
            values = [v for v in (int_constant(a) for a in node.args) if v is not None]
            return len(values) == len(node.args) and len(range(*values[:3])) > 0
    return False


def int_constant(node: ast.AST) -> int | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, int):
        return node.value
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        inner = int_constant(node.operand)
        return -inner if inner is not None else None
    return None


def container_names(nodes) -> set[str]:
    """Module-level names bound to a mutable container: {}, [], set(), dict(), defaultdict(list), and similar."""
    names: set[str] = set()
    for node in nodes:
        value = node.value if isinstance(node, (ast.Assign, ast.AnnAssign)) else None
        targets = node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
        if isinstance(value, (ast.Dict, ast.List, ast.Set)) or (isinstance(value, ast.Call) and last_name(value.func) in CONTAINER_CALLS):
            names.update(t.id for t in targets if isinstance(t, ast.Name))
    return names


def returns_value(func) -> bool:
    """True when a fixture returns or yields something other than None."""
    for node in walk_own(func):
        if isinstance(node, (ast.Return, ast.Yield)) and node.value is not None:
            if not (isinstance(node.value, ast.Constant) and node.value.value is None):
                return True
    return False


def round_trip_partner(name: str, called: set[str]) -> str | None:
    """A called name that undoes `name`: encode_x for decode_x, from_json for to_json, y_to_x for x_to_y."""
    parts = name.split("_")
    for i, part in enumerate(parts):
        partner = ROUND_TRIP_VERBS.get(part)
        if partner:
            candidate = "_".join(parts[:i] + [partner] + parts[i + 1:])
            if candidate != name and candidate in called:
                return candidate
    if "to" in parts[1:-1]:
        i = parts.index("to", 1)
        swapped = "_".join(parts[i + 1:] + ["to"] + parts[:i])
        if swapped != name and swapped in called:
            return swapped
    return None


def literal_names(nodes) -> set[str]:
    names: set[str] = set()
    for node in nodes:
        if isinstance(node, ast.Assign) and non_empty_literal(node.value, names):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
    return names


def is_fixture(func) -> bool:
    return any(dotted(d).endswith("fixture") for d in func.decorator_list)


def fixture_args(func) -> dict:
    for d in func.decorator_list:
        if isinstance(d, ast.Call) and dotted(d.func).endswith("fixture"):
            return {kw.arg: kw.value.value for kw in d.keywords if kw.arg in ("scope", "autouse", "name") and isinstance(kw.value, ast.Constant)}
    return {}


def call_matches(name: str, targets: set[str]) -> bool:
    return name in targets or any(name.endswith("." + t) for t in targets if "." in t)


class LiteralStripper(ast.NodeTransformer):
    def visit_Constant(self, node: ast.Constant):
        if isinstance(node.value, bool) or node.value is None:
            return node
        return ast.copy_location(ast.Constant(value="<lit>"), node)


def body_fingerprint(func, strip_literals: bool) -> str | None:
    body = [s for i, s in enumerate(func.body) if not (i == 0 and is_docstring(s))]
    if len(body) < 2:
        return None
    body = [copy.deepcopy(s) for s in body]
    if strip_literals:
        body = [LiteralStripper().visit(s) for s in body]
    dumped = "\n".join(ast.dump(s, annotate_fields=False, include_attributes=False) for s in body)
    if not strip_literals:
        # Identical bodies with different parameters or parametrisation test different inputs.
        signature = [ast.dump(func.args, annotate_fields=False, include_attributes=False)]
        signature += [ast.dump(d, annotate_fields=False, include_attributes=False) for d in func.decorator_list]
        dumped += "\n" + "\n".join(signature)
    return hashlib.sha1(dumped.encode()).hexdigest()


def is_skip_call(node: ast.Call) -> bool:
    name = dotted(node.func)
    return last_name(node.func) in SKIP_CALLS and (name in SKIP_CALLS or name.startswith(("pytest.", "self.", "unittest.")))


def has_assertion(nodes: list[ast.AST], helpers: set[str]) -> bool:
    return assertion_count(nodes, helpers, stop_at_first=True) > 0


def assertion_count(nodes: list[ast.AST], helpers: set[str], stop_at_first: bool = False) -> int:
    count = 0
    for node in nodes:
        if is_assertion(node, helpers):
            count += 1
            if stop_at_first:
                break
    return count


def is_assertion(node: ast.AST, helpers: set[str]) -> bool:
    """One assert statement or assertion-like call. `with pytest.raises(...)` counts once, through its call."""
    if isinstance(node, ast.Assert):
        return True
    if isinstance(node, ast.Call):
        name = last_name(node.func)
        if isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Call) and dotted(node.func.value.func) == "super":
            return True  # super().test_x(): the parent test does the checking
        return bool(
            name.startswith("assert")
            or name in ASSERT_CONTEXTS
            or name in FAIL_CALLS
            or name in helpers
            or MOCK_ASSERT_RE.match(name)
            or ASSERT_HELPER_RE.match(name)
            or RAISES_WARNS_RE.search(name)
        )
    if isinstance(node, ast.Compare):
        return any(dotted(c).endswith("snapshot") for c in node.comparators)
    return False


def is_weak_assert(node: ast.Assert) -> bool:
    """An assert that checks only existence or type, such as `assert x`, `x is not None`, or `len(x) > 0`."""
    test = node.test
    if isinstance(test, (ast.Name, ast.Attribute)):
        return True
    if isinstance(test, ast.Call) and last_name(test.func) in ("isinstance", "hasattr", "callable", "bool"):
        return True
    if isinstance(test, ast.Compare) and len(test.ops) == 1:
        op, right = test.ops[0], test.comparators[0]
        if isinstance(op, ast.IsNot) and isinstance(right, ast.Constant) and right.value is None:
            return True
        if isinstance(test.left, ast.Call) and last_name(test.left.func) == "len" and isinstance(right, ast.Constant):
            return (isinstance(op, ast.Gt) and right.value == 0) or (isinstance(op, ast.GtE) and right.value == 1) or (isinstance(op, ast.NotEq) and right.value == 0)
    return False


def existence_only(node: ast.AST) -> bool | None:
    """True for an assertion that checks only that something exists; False for any other assertion.

    Stricter than is_weak_assert: a bare `assert user.is_active` is a real check, and so is
    isinstance, which is often the behaviour under test. Only `is not None`, hasattr,
    len(x) > 0, and assertIsNotNone count.
    """
    if isinstance(node, ast.Assert):
        test = node.test
        if isinstance(test, ast.Call) and last_name(test.func) == "hasattr":
            return True
        if isinstance(test, ast.Compare) and len(test.ops) == 1:
            op, right = test.ops[0], test.comparators[0]
            if isinstance(op, ast.IsNot) and isinstance(right, ast.Constant) and right.value is None:
                return True
            if isinstance(test.left, ast.Call) and last_name(test.left.func) == "len" and isinstance(right, ast.Constant):
                return (isinstance(op, ast.Gt) and right.value == 0) or (isinstance(op, ast.GtE) and right.value == 1) or (isinstance(op, ast.NotEq) and right.value == 0)
        return False
    if isinstance(node, ast.Call) and last_name(node.func) == "assertIsNotNone":
        return True
    return False


def is_bare_skip(decorator: ast.AST) -> bool:
    """`@skip` or `@unittest.skip` used without a reason; pytest.mark.skip is a marker and works bare."""
    return not isinstance(decorator, ast.Call) and dotted(decorator) in ("skip", "unittest.skip", "pytest.skip")


def looks_like_message(node: ast.AST) -> bool:
    """A failure message rather than a value to compare: a string, an f-string, % or .format, str(...), or a msg name."""
    if isinstance(node, ast.JoinedStr) or (isinstance(node, ast.Constant) and isinstance(node.value, str)):
        return True
    if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Mod, ast.Add)):
        return looks_like_message(node.left) or looks_like_message(node.right)
    if isinstance(node, ast.Call):
        if isinstance(node.func, ast.Attribute) and node.func.attr in ("format", "join") and looks_like_message(node.func.value):
            return True
        return last_name(node.func) in ("str", "repr", "format")
    if isinstance(node, (ast.Name, ast.Attribute)):
        name = last_name(node).lower()
        return any(word in name for word in ("msg", "message", "reason", "error", "err", "explain", "detail", "hint"))
    return False


def tautology(node: ast.Assert) -> str | None:
    test = node.test
    if isinstance(test, ast.Constant) and test.value:
        return "asserts a truthy constant"
    if isinstance(test, ast.Tuple) and test.elts:
        return "asserts a non-empty tuple, which is always true"
    if isinstance(test, (ast.List, ast.Set)) and test.elts or isinstance(test, ast.Dict) and test.keys:
        return "asserts a non-empty literal, which is always true"
    return None


def self_comparison(node: ast.Assert) -> bool:
    """x == x is always true for built-in values, but it can be a deliberate test of a custom __eq__."""
    test = node.test
    if isinstance(test, ast.Compare) and len(test.ops) == 1 and isinstance(test.ops[0], (ast.Eq, ast.Is)):
        left, right = test.left, test.comparators[0]
        return ast.dump(left) == ast.dump(right) and not any(isinstance(n, ast.Call) for n in ast.walk(left))
    return False


