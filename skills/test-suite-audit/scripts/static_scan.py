def tamper_diff(before: dict, after: dict) -> dict:
    """Compare two scans: removed tests, new skips and xfails, lost assertions, and discovery changes."""
    b, a = before.get("tests", {}), after.get("tests", {})
    removed = sorted(set(b) - set(a))
    added = sorted(set(a) - set(b))
    added_by_hash = {a[t]["hash"]: t for t in added}
    moved = {t: added_by_hash[b[t]["hash"]] for t in removed if b[t]["hash"] in added_by_hash}
    removed = [t for t in removed if t not in moved]
    added = [t for t in added if t not in set(moved.values())]
    common = sorted(set(b) & set(a)) + [t for t in moved]
    after_of = {t: a[moved.get(t, t)] for t in common}
    newly_skipped = [t for t in common if not (b[t]["skip"] or b[t]["skip_call"]) and (after_of[t]["skip"] or after_of[t]["skip_call"])]
    newly_xfail = [t for t in common if not b[t]["xfail"] and after_of[t]["xfail"]]
    fewer_asserts = [
        {"test": t, "before": b[t]["assertions"], "after": after_of[t]["assertions"]}
        for t in common
        if after_of[t]["assertions"] < b[t]["assertions"]
    ]
    weaker_asserts = [
        {"test": t, "strong_before": b[t].get("strong_asserts", 0), "strong_after": after_of[t].get("strong_asserts", 0)}
        for t in common
        if after_of[t].get("strong_asserts", 0) < b[t].get("strong_asserts", 0) and after_of[t]["assertions"] >= b[t]["assertions"]
    ]
    config = {
        k: {"before": before.get("config", {}).get(k), "after": after.get("config", {}).get(k)}
        for k in NARROWING_KEYS
        if before.get("config", {}).get(k) != after.get("config", {}).get(k)
    }
    narrowing = []
    before_opts, after_opts = before.get("config", {}).get("addopts", []), after.get("config", {}).get("addopts", [])
    for token in after_opts:
        if token not in before_opts and token.split("=", 1)[0] in NARROWING_OPTIONS:
            narrowing.append(token)
    weakened = bool(removed or newly_skipped or newly_xfail or fewer_asserts or weaker_asserts or config or narrowing)
    return {
        "removed": removed,
        "added": added,
        "moved": moved,
        "newly_skipped": newly_skipped,
        "newly_xfail": newly_xfail,
        "fewer_assertions": fewer_asserts,
        "weaker_assertions": weaker_asserts,
        "discovery_config_changed": config,
        "narrowing_addopts": narrowing,
        "weakened": weakened,
    }


def cmd_diff(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="static_scan.py diff", description="Tamper check: compare two scans taken before and after a change.")
    parser.add_argument("before", help="--json-out of a scan before the change")
    parser.add_argument("after", help="--json-out of a scan after the change")
    parser.add_argument("--json-out")
    args = parser.parse_args(argv)
    result = tamper_diff(json.loads(Path(args.before).read_text()), json.loads(Path(args.after).read_text()))
    print(
        f"tests removed: {len(result['removed'])}   added: {len(result['added'])}   moved or renamed: {len(result['moved'])}   "
        f"newly skipped: {len(result['newly_skipped'])}   newly xfail: {len(result['newly_xfail'])}   fewer assertions: {len(result['fewer_assertions'])}   "
        f"weaker assertions: {len(result['weaker_assertions'])}"
    )
    for t in result["removed"][:8]:
        print(f"  removed: {t}")
    for t in (result["newly_skipped"] + result["newly_xfail"])[:8]:
        print(f"  now skipped or xfail: {t}")
    for row in result["fewer_assertions"][:8]:
        print(f"  assertions {row['before']} -> {row['after']}: {row['test']}")
    for row in result["weaker_assertions"][:8]:
        print(f"  strong assertions {row['strong_before']} -> {row['strong_after']} (a check became 'is not None', truthiness, or similar): {row['test']}")
    for token in result["narrowing_addopts"]:
        print(f"  addopts gained {token!r}, which runs fewer tests or hides failures")
    for key, change in result["discovery_config_changed"].items():
        print(f"  discovery setting {key}: {change['before']} -> {change['after']}")
    print("verdict: " + ("WEAKENED – every item above needs the user's explicit approval" if result["weakened"] else "no weakening found"))
    if args.json_out:
        write_out(args.json_out, json.dumps(result, indent=2))
        print(f"json: {args.json_out}")
    return 1 if result["weakened"] else 0


def write_out(path_text: str, text: str) -> None:
    path = Path(path_text)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv[:1] == ["diff"]:
        return cmd_diff(argv[1:])
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("paths", nargs="*", help="test directories or files (default: testpaths, or .)")
    parser.add_argument("--config", default=".", help="directory holding the pytest configuration (default: .)")
    parser.add_argument("--runner", choices=("pytest", "unittest"), default="pytest", help="discovery rules to apply")
    parser.add_argument("--nodeids", help="output of `pytest --collect-only -q`, to find tests that are never collected")
    parser.add_argument("--blame", action="store_true", help="add the last-change date to skip and xfail examples")
    parser.add_argument("--examples", type=int, default=3, help="examples to keep per check (default 3)")
    parser.add_argument("--json-out", help="write the full result as JSON")
    args = parser.parse_args(argv)

    config_dir = Path(args.config).resolve()
    config = read_pytest_config(config_dir)
    roots = [Path(p) for p in args.paths] or [config_dir / p for p in config["testpaths"]]
    roots = [r for r in roots if r.exists()] or [config_dir]
    scanner = Scanner(config, args.runner, args.examples)
    files = scanner.walk(roots)
    bases_of = class_bases(files)
    scanner.testcase_classes = inheritors(bases_of, lambda b: b.endswith("TestCase"))
    scanner.transactional_classes = inheritors(bases_of, lambda b: b in TRANSACTIONAL_BASES)
    cwd = Path.cwd().resolve()
    for path in files:
        try:
            rel = str(path.resolve().relative_to(cwd))
        except ValueError:
            rel = str(path)
        scanner.scan_file(path, rel)
    scanner.finish(args.nodeids)
    scanner.report_excluded_dirs(cwd)
    if args.blame:
        for check in ("skip-unconditional", "xfail-not-strict"):
            if check in scanner.checks:
                scanner.checks[check]["examples"] = blame_dates(scanner.checks[check]["examples"])

    inv = dict(scanner.inventory)
    result = {
        "config": config,
        "runner": args.runner,
        "roots": [str(r) for r in roots],
        "files_scanned": len(files),
        "parse_errors": scanner.parse_errors,
        "inventory": inv,
        "largest_test_files": [{"path": p, "lines": n} for n, p in sorted(scanner.file_sizes, reverse=True)[:10]],
        "conftest_files": sorted(scanner.conftests, key=lambda c: -c["lines"]),
        "fixtures_defined": sum(len(v) for v in scanner.fixtures.values()),
        "top_skip_reasons": sorted(scanner.skip_reasons.items(), key=lambda kv: -kv[1])[:10],
        "checks": {k: v for k, v in sorted(scanner.checks.items()) if v["count"]},
        "tests": scanner.tests,
        "caveat": "Static counts are estimates. Confirm each candidate by reading the code or running it before you report it.",
    }
    print(f"config: {config['source'] or 'none found (pytest defaults)'}   runner rules: {args.runner}")
    print(
        f"scanned {len(files)} files: {inv.get('test_files', 0)} test files, {inv.get('test_functions', 0)} test functions "
        f"(static estimate), {inv.get('test_classes', 0)} classes, {result['fixtures_defined']} fixtures, {len(scanner.conftests)} conftest files"
    )
    if inv.get("parametrized_tests"):
        print(f"parametrised tests: {inv['parametrized_tests']}, expanding to about {inv['parametrize_cases_estimate']} cases")
    if inv.get("hypothesis_tests"):
        print(f"property-based tests (@given): {inv['hypothesis_tests']}")
    if scanner.parse_errors:
        print(f"parse errors: {len(scanner.parse_errors)} (try the project's Python), for example {scanner.parse_errors[0][:120]}")
    for name, entry in sorted(result["checks"].items(), key=lambda kv: -kv[1]["count"])[:24]:
        print(f"{name}: {entry['count']}")
        for ex in entry["examples"][:2]:
            print(f"    {ex[:170]}")
    if args.json_out:
        write_out(args.json_out, json.dumps(result, indent=2))
        print(f"json: {args.json_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
