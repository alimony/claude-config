def read_toml_section(path: Path, where: tuple[str, ...]) -> dict | None:
    text = path.read_text(errors="replace")
    try:
        import tomllib  # Python 3.11+

        node = tomllib.loads(text)
        for key in where:
            node = node.get(key) if isinstance(node, dict) else None
        if not isinstance(node, dict):
            return None
        if isinstance(node.get("ini_options"), dict):
            # pyproject.toml: [tool.pytest] (pytest 9) and [tool.pytest.ini_options] both count.
            node = {**node["ini_options"], **{k: v for k, v in node.items() if k != "ini_options"}}
        return node
    except Exception:
        headers = ["pytest"] if where == ("pytest",) else ["tool.pytest", "tool.pytest.ini_options"]
        section: dict | None = None
        for header in headers:
            m = re.search(rf"^\[{re.escape(header)}\]\s*$(.*?)(?=^\[|\Z)", text, re.M | re.S)
            if not m:
                continue
            section = section or {}
            for key in CONFIG_KEYS:
                km = re.search(rf"^{key}\s*=\s*(\[.*?\]|\".*?\"|'.*?'|\S+)", m.group(1), re.M | re.S)
                if km:
                    raw = km.group(1)
                    section[key] = re.findall(r"[\"']([^\"']+)[\"']", raw) if raw.startswith("[") else raw.strip("\"'")
        return section


def read_pytest_config(config_dir: Path) -> dict:
    """Read the pytest keys the scan needs from the first configuration file, in pytest 9's order."""
    for name, kind, where in CONFIG_FILES:
        path = config_dir / name
        if not path.is_file():
            continue
        if kind == "toml":
            section = read_toml_section(path, where)  # type: ignore[arg-type]
            if section is None:
                continue
            return normalise_config({k: section[k] for k in CONFIG_KEYS if k in section}, str(path))
        parser = configparser.ConfigParser(interpolation=None)
        try:
            parser.read(path)
        except configparser.Error:
            continue
        if parser.has_section(where):  # type: ignore[arg-type]
            return normalise_config({k: parser.get(where, k) for k in CONFIG_KEYS if parser.has_option(where, k)}, str(path))  # type: ignore[arg-type]
    return normalise_config({}, None)


def normalise_config(raw: dict, source: str | None) -> dict:
    def as_list(value, default):
        if value is None:
            return list(default)
        if isinstance(value, str):
            return value.split()
        return [str(v) for v in value]

    def truthy(value) -> bool:
        return value is True or str(value).lower() in ("true", "1", "yes")

    strict = any(truthy(raw.get(k)) for k in ("xfail_strict", "strict_xfail", "strict") if raw.get(k) is not None)
    return {
        "source": source,
        "python_files": as_list(raw.get("python_files"), DEFAULT_FILES),
        "python_classes": as_list(raw.get("python_classes"), DEFAULT_CLASSES),
        "python_functions": as_list(raw.get("python_functions"), DEFAULT_FUNCTIONS),
        "testpaths": as_list(raw.get("testpaths"), []),
        "norecursedirs": as_list(raw.get("norecursedirs"), DEFAULT_NORECURSE),
        "xfail_strict": strict,
        "addopts": as_list(raw.get("addopts"), []),
        "filterwarnings": as_list(raw.get("filterwarnings"), []) if not isinstance(raw.get("filterwarnings"), str) else raw["filterwarnings"].splitlines(),
    }


def glob_match(name: str, patterns: list[str]) -> bool:
    return any(fnmatch.fnmatch(name, p) for p in patterns)


def name_match(name: str, patterns: list[str]) -> bool:
    """pytest's rule: patterns with glob characters are globs, others are prefixes."""
    for pattern in patterns:
        if any(c in pattern for c in "*?["):
            if fnmatch.fnmatch(name, pattern):
                return True
        elif name.startswith(pattern):
            return True
    return False


# --------------------------------------------------------------------------- AST helpers


def dotted(node: ast.AST) -> str:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        base = dotted(node.value)
        return f"{base}.{node.attr}" if base else node.attr
    if isinstance(node, ast.Call):
        return dotted(node.func)
    return ""


def last_name(node: ast.AST) -> str:
    return dotted(node).rsplit(".", 1)[-1]


def source_of(node: ast.AST, limit: int = 100) -> str:
    """Source text of a node (Python 3.9+), cut to `limit` characters."""
    text = ast.unparse(node) if hasattr(ast, "unparse") else (dotted(node) or type(node).__name__)
    return text if len(text) <= limit else text[: limit - 1] + "…"


def is_docstring(stmt: ast.stmt) -> bool:
    return isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, str)


def walk_body(func) -> list[ast.AST]:
    """All nodes in a function body, excluding its decorators and signature."""
    nodes = []
    for stmt in func.body:
        nodes.extend(ast.walk(stmt))
    return nodes


def walk_own(func) -> list[ast.AST]:
    """Nodes in a function's own body, without nested functions, lambdas, or classes."""
    nested = (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda, ast.ClassDef)
    out, stack = [], [s for s in func.body if not isinstance(s, nested)]
    while stack:
        node = stack.pop()
        out.append(node)
        for child in ast.iter_child_nodes(node):
            if not isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda, ast.ClassDef)):
                stack.append(child)
    return out


