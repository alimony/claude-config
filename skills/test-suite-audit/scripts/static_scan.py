#!/usr/bin/env python3
"""Scan Python test files statically and report audit candidates as JSON.

This covers what linters do not. Run ruff for the rest, for example:
    uvx ruff check --select F811,F631,B011,B015,B017,PGH005,PT --statistics TESTS

Checks, each reported with a count and a few examples:
  no-assertion          tests with no assert, pytest.raises, assert* call, or asserting helper
  tautology             asserts that cannot fail (truthy constants, non-empty tuple, list, set, or dict literals)
  self-comparison       assert x == x: a tautology for built-in values, but possibly a test of a custom __eq__
  assert-in-except      asserts only in an except block, so the test passes when nothing is raised
  unreachable-assert    asserts after a return or raise in the same block
  shadowed-test         a test name defined twice in one scope, so only the last one runs
  exact-duplicate-body  tests in one file with identical bodies and different names (often a copy never edited)
  cross-file-duplicate-body  identical bodies in different files (weaker: imports and fixtures may differ)
  literal-only-body     tests whose bodies differ only in literals (parametrize candidates)
  uncollectable-class   test classes with __init__ (own, inherited, or generated by dataclass or attrs)
  module-disabled       modules that set __test__ = False, so none of their tests run
  disabled-class        classes with __test__ = False that no scanned class inherits from
  in-norecursedirs      test functions under directories that an explicit norecursedirs excludes
  yield-in-test, returns-value, empty-parametrize, assert-only-in-loop, assert-true-two-args, imported-test
                        tests that never run, run twice, or cannot fail
  mock-typo             .called_once_with() and similar, which check nothing (Python 3.12+ raises instead)
  weak-assertions       tests that end on an assertion, and whose every assertion checks only that a
                        result exists: is not None, hasattr, len(x) > 0, assertIsNotNone
  xfail-never-runs      xfail(run=False): the body never runs
  misnamed-test         misspelt test names (tset_, tst_, ...), and methods with asserts whose names miss the test pattern
  bare-skip-decorator   @skip or @unittest.skip without a reason, which replaces the class or test with a
                        function, so its tests never run and never show as skipped
  file-not-collected    files with test functions whose names do not match the runner's file pattern
  not-run-by-runner     with --runner unittest: module-level test functions and non-TestCase classes, which never run
  not-collected         tests defined in the code but absent from --nodeids
  skip-unconditional, xfail-not-strict, skip-inside-test   unconditional skips, pytest xfail markers
                        without strict, and unconditional skip() calls; conditional skips are only counted
  autouse-fixtures      autouse fixtures, their scope, and roughly how many tests they reach
  unused-fixtures       fixtures never requested by name (approximate; confirm with pytest-deadfixtures)
  unread-fixture        tests that request a fixture that returns a value, and never read it: its setup
                        is paid for its side effects only, or for nothing
  risk-*                sleeps, real clocks, unseeded randomness, network, subprocess, threads, env, and
                        global state: `global` statements, writes to the test module's module-level
                        containers, and attributes of imported modules set without monkeypatch
  transactional-tests   Django TransactionTestCase or LiveServerTestCase (also through project base
                        classes), django_db(transaction=True), django_db(True), reset_sequences=True,
                        pytestmark, and the transactional_db, live_server, and django_db_reset_sequences
                        fixtures, including fixtures that request them
  mock-density          tests with five or more patches
  parametrize-size      parametrize matrices of 50 or more cases, including stacked decorators
  hypothesis-settings   @settings on property tests (max_examples, deadline, suppressed health checks),
                        and settings.register_profile and load_profile calls
  pbt-candidates        tests that call both halves of a round trip, such as dumps and loads, or
                        encode_order and decode_order

Usage:
    static_scan.py [PATH ...] [--config DIR] [--runner pytest|unittest] [--nodeids FILE]
                   [--blame] [--examples N] [--json-out FILE]
    static_scan.py diff BEFORE_JSON AFTER_JSON [--json-out FILE]

`diff` is the tamper check for any change to the suite, including your own:
it lists removed tests (matching moved or renamed ones by body), new skips and
xfails, tests with fewer assertions or with checks weakened to truthiness or
"is not None", changed discovery settings, and addopts that run fewer tests or
hide failures. It exits with 1 when it finds any of these. It cannot see
product code that special-cases tests (grep for PYTEST_CURRENT_TEST), coverage
thresholds, or pragma: no cover.

Run it from the pytest rootdir, so paths match node IDs. PATH defaults to the
configured testpaths, or the current directory. pytest's python_files,
python_classes, python_functions, testpaths, norecursedirs, and xfail_strict
are read from pyproject.toml, pytest.ini, tox.ini, or setup.cfg in --config.
With --runner unittest (Django's runner, `python -m unittest`), discovery
follows unittest's rules instead: files matching test*.py, TestCase
subclasses, and methods starting with "test".

For --nodeids, use `pytest --collect-only -q` without -m or -k, so deselected
tests still count as collected.

Counts are static estimates. Inherited test methods, custom collectors, and
parametrisation make them differ from the collected count, so never report a
static count as the number of tests.

Run it with the project's own Python when you can: a file that uses syntax
newer than the interpreter is listed under parse_errors, not scanned.

Standard library only; runs on Python 3.8+.
"""
